    public function templateFieldGroup(string $field, string $dataType): string
    {
        $field = trim($field);
        if ($field === '') {
            return '';
        }

        $option = $this->call('systemFieldOptionsByValue', $dataType)[$field] ?? null;

        return is_array($option) ? (string) ($option['group'] ?? '') : '';
    }

